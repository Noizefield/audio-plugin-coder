<#
.SYNOPSIS
    Wire the Open Design (OpenDesign) MCP server into this repo's coding agents.
.DESCRIPTION
    OpenDesign ships a stdio MCP server (`od mcp --daemon-url ...`) that proxies
    project/files/skills tool calls to a running local OpenDesign daemon. This
    script installs nothing from the network: it locates an existing Open Design
    desktop install, creates an `od` shim on PATH, and writes machine-local MCP
    config for the hosts that read repo-level config.

    Generated files are gitignored on purpose (they contain machine paths):
        <repo>\.mcp.json          Claude Code / generic MCP hosts
        <repo>\.cursor\mcp.json   Cursor
        <repo>\.vscode\mcp.json   VS Code (native MCP / Copilot)
        <repo>\.codex\config.toml Codex CLI ([mcp_servers."open-design"] appended)
        <PathDir>\od.cmd|od.ps1   `od` shim -> bundled daemon-cli.mjs

    The OpenDesign daemon must be running (open the Open Design app) before the
    MCP tools can reach projects; the MCP process itself starts either way.
.PARAMETER InstallRoot
    Open Design install folder. Auto-detected under %LOCALAPPDATA%\Programs,
    %ProgramFiles%, and %ProgramFiles(x86)% when omitted.
.PARAMETER PathDir
    Folder that receives the `od` shim. Default: %APPDATA%\npm (already on PATH).
.PARAMETER DaemonUrl
    URL of the running OpenDesign daemon. Default: http://127.0.0.1:7456
.PARAMETER Uninstall
    Remove the shim and the generated config files instead of installing.
.PARAMETER SkipVerify
    Skip the MCP initialize/tools-list handshake check.
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File .\scripts\install-open-design-mcp.ps1
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File .\scripts\install-open-design-mcp.ps1 -Uninstall
#>
[CmdletBinding()]
param(
    [string]$InstallRoot,
    [string]$PathDir = (Join-Path $env:APPDATA "npm"),
    # Empty = let scripts/lib/od-mcp-bridge.mjs discover the live daemon port,
    # which is what the desktop app randomises on every launch.
    [string]$DaemonUrl = "",
    [switch]$Uninstall,
    [switch]$SkipVerify
)

$ErrorActionPreference = "Stop"

$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
$DaemonCliRelative = "resources\app\prebundled\daemon\daemon-cli.mjs"
$BridgePath = Join-Path $RepoRoot "scripts\lib\od-mcp-bridge.mjs"

# Files this script owns (installed and removed as a set). Key = root object name
# each host expects: Claude Code / Cursor use "mcpServers", VS Code uses "servers".
$ConfigTargets = @(
    @{ Path = (Join-Path $RepoRoot ".mcp.json");          Key = "mcpServers" }
    @{ Path = (Join-Path $RepoRoot ".cursor\mcp.json");   Key = "mcpServers" }
    @{ Path = (Join-Path $RepoRoot ".vscode\mcp.json");   Key = "servers" }
)
$CodexConfig = Join-Path $RepoRoot ".codex\config.toml"
$CodexHeader = '# --- Open Design MCP (machine-local, generated by scripts/install-open-design-mcp.ps1) ---'
$ShimFiles = @((Join-Path $PathDir "od.cmd"), (Join-Path $PathDir "od.ps1"))

function Write-Step([string]$Message) { Write-Host "  [apc] $Message" -ForegroundColor Cyan }
function Write-Ok([string]$Message) { Write-Host "  [ok ] $Message" -ForegroundColor Green }
function Write-Warn2([string]$Message) { Write-Host "  [warn] $Message" -ForegroundColor Yellow }

function Find-OpenDesignInstall {
    param([string]$Explicit)

    if ($Explicit) {
        $cli = Join-Path $Explicit $DaemonCliRelative
        if (-not (Test-Path $cli)) {
            throw "Not an Open Design install: '$cli' not found. Expected the desktop app folder."
        }
        return (Resolve-Path $Explicit).Path
    }

    $candidates = @(
        (Join-Path $env:LOCALAPPDATA "Programs\Open Design"),
        (Join-Path $env:ProgramFiles "Open Design"),
        (Join-Path ${env:ProgramFiles(x86)} "Open Design")
    )
    foreach ($candidate in $candidates) {
        if ($candidate -and (Test-Path (Join-Path $candidate $DaemonCliRelative))) {
            return (Resolve-Path $candidate).Path
        }
    }

    # Fall back to a shallow scan (covers renamed install folders).
    $scanRoots = @((Join-Path $env:LOCALAPPDATA "Programs"), $env:ProgramFiles)
    foreach ($root in $scanRoots) {
        if (-not $root -or -not (Test-Path $root)) { continue }
        $hit = Get-ChildItem -Path $root -Directory -ErrorAction SilentlyContinue |
            Where-Object { $_.Name -match 'open\s*-?\s*design' } |
            Where-Object { Test-Path (Join-Path $_.FullName $DaemonCliRelative) } |
            Select-Object -First 1
        if ($hit) { return $hit.FullName }
    }

    throw "Open Design desktop install not found. Install it from https://open-design.ai/download or pass -InstallRoot <folder>."
}

function Find-NodeExe {
    $cmd = Get-Command node.exe -ErrorAction SilentlyContinue
    if ($cmd) { return $cmd.Source }
    $cmd = Get-Command node -ErrorAction SilentlyContinue
    if ($cmd) { return $cmd.Source }
    $fallback = Join-Path $env:ProgramFiles "nodejs\node.exe"
    if (Test-Path $fallback) { return $fallback }
    throw "node.exe not found on PATH. OpenDesign's MCP server is a Node process; install Node.js 20+."
}

function ConvertTo-FwdSlash([string]$Path) { return ($Path -replace '\\', '/') }


function Install-OdShim {
    param([string]$NodeExe, [string]$DaemonCli)

    if (-not (Test-Path $PathDir)) { New-Item -ItemType Directory -Path $PathDir -Force | Out-Null }

    $cmdBody = @"
@echo off
rem Generated by scripts/install-open-design-mcp.ps1 - Open Design CLI shim
"$NodeExe" "$DaemonCli" %*
"@
    Set-Content -Path (Join-Path $PathDir "od.cmd") -Value $cmdBody -Encoding ASCII

    $ps1Body = @"
# Generated by scripts/install-open-design-mcp.ps1 - Open Design CLI shim
& '$NodeExe' '$DaemonCli' @args
exit `$LASTEXITCODE
"@
    Set-Content -Path (Join-Path $PathDir "od.ps1") -Value $ps1Body -Encoding UTF8

    Write-Ok "od shim -> $PathDir"
}

function Build-McpArgs {
    # The bridge discovers the daemon port at spawn time; an explicit -DaemonUrl
    # pins it and skips discovery. The [object[]] cast is required: PowerShell
    # otherwise collapses a single-element array into a JSON string, which hosts
    # reject ("args" must be an array).
    param([string]$Bridge, [string]$Url)
    [object[]]$args = @(ConvertTo-FwdSlash $Bridge)
    if ($Url) { $args = @($args + @("--daemon-url", $Url)) }
    return , $args
}

function Set-McpConfig {
    param([string]$ConfigPath, [string]$RootKey, [string]$NodeExe, [string]$Bridge, [string]$Url)

    $dir = Split-Path -Parent $ConfigPath
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }

    # Preserve unrelated servers already configured in this file.
    $root = $null
    if (Test-Path $ConfigPath) {
        try {
            $root = Get-Content -Path $ConfigPath -Raw | ConvertFrom-Json
        } catch {
            Write-Warn2 "Existing $ConfigPath is not valid JSON - replacing it."
            $root = $null
        }
    }
    if (-not $root) { $root = [pscustomobject]@{} }

    $entry = [ordered]@{
        type    = "stdio"
        command = (ConvertTo-FwdSlash $NodeExe)
        args    = [object[]](Build-McpArgs -Bridge $Bridge -Url $Url)
    }

    $root | Add-Member -NotePropertyName $RootKey -NotePropertyValue ([pscustomobject]@{
        "open-design" = [pscustomobject]$entry
    }) -Force

    ($root | ConvertTo-Json -Depth 8) | Set-Content -Path $ConfigPath -Encoding UTF8
    Write-Ok "MCP config -> $ConfigPath"
}

function Remove-CodexBlock {
    # Strips our generated header + [mcp_servers."open-design"] table.
    if (-not (Test-Path $CodexConfig)) { return $false }
    $lines = Get-Content $CodexConfig
    $kept = New-Object System.Collections.Generic.List[string]
    $skipping = $false
    $found = $false
    foreach ($line in $lines) {
        if ($line -eq $CodexHeader) { $skipping = $true; $found = $true; continue }
        if ($skipping -and $line -match '^\s*\[') { $skipping = $false }
        if ($skipping) { continue }
        if ($line -match '^\[mcp_servers\."open-design"\]') { $skipping = $true; $found = $true; continue }
        $kept.Add($line)
    }
    if ($found) { Set-Content -Path $CodexConfig -Value $kept -Encoding UTF8 }
    return $found
}

function Set-CodexConfig {
    param([string]$NodeExe, [string]$Bridge, [string]$Url)

    $dir = Split-Path -Parent $CodexConfig
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }

    # Refresh our own block in place so a changed bridge path never goes stale.
    if (Remove-CodexBlock) { Write-Step "refreshing existing Open Design block in .codex\config.toml" }

    $argList = (Build-McpArgs -Bridge $Bridge -Url $Url) | ForEach-Object { '"' + $_ + '"' }
    $block = @"

$CodexHeader
[mcp_servers."open-design"]
command = "$(ConvertTo-FwdSlash $NodeExe)"
args = [$($argList -join ', ')]
"@
    Add-Content -Path $CodexConfig -Value $block -Encoding UTF8
    Write-Ok "MCP config -> $CodexConfig"
}

function Test-OdMcpServer {
    param([string]$NodeExe, [string]$Bridge, [string]$Url)

    $requests = @(
        '{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2024-11-05","capabilities":{},"clientInfo":{"name":"apc-installer","version":"1.0"}}}'
        '{"jsonrpc":"2.0","method":"notifications/initialized"}'
        '{"jsonrpc":"2.0","id":2,"method":"tools/list"}'
    ) -join "`n"

    # File-redirected stdio keeps the capture deterministic (a PowerShell pipeline
    # can drop the earliest JSON-RPC frame when the child is a Node process).
    $tmpIn = Join-Path ([System.IO.Path]::GetTempPath()) ("apc-od-in-" + [guid]::NewGuid().ToString("N") + ".jsonl")
    $tmpOut = Join-Path ([System.IO.Path]::GetTempPath()) ("apc-od-out-" + [guid]::NewGuid().ToString("N") + ".log")
    $tmpErr = Join-Path ([System.IO.Path]::GetTempPath()) ("apc-od-err-" + [guid]::NewGuid().ToString("N") + ".log")
    $output = ""
    $result = [ordered]@{ Ok = $false; Daemon = "" }
    try {
        Set-Content -Path $tmpIn -Value $requests -Encoding ASCII
        $pinned = @(Build-McpArgs -Bridge $Bridge -Url $Url | Select-Object -Skip 1)
        $argLine = ('"{0}"' -f $Bridge)
        if ($pinned.Count -gt 0) { $argLine += ' ' + ($pinned -join ' ') }
        $proc = Start-Process -FilePath $NodeExe -ArgumentList $argLine `
            -RedirectStandardInput $tmpIn -RedirectStandardOutput $tmpOut -RedirectStandardError $tmpErr `
            -NoNewWindow -PassThru
        if (-not $proc.WaitForExit(60000)) {
            try { $proc.Kill() } catch { }
            Write-Warn2 "MCP server did not exit within 60s during the handshake probe."
            return $result
        }
        if (Test-Path $tmpOut) { $output += (Get-Content -Path $tmpOut -Raw) }
        if (Test-Path $tmpErr) { $output += (Get-Content -Path $tmpErr -Raw) }
    } finally {
        Remove-Item -LiteralPath $tmpIn, $tmpOut, $tmpErr -Force -ErrorAction SilentlyContinue
    }

    if ($env:APC_OD_DEBUG) {
        Write-Host "    DBG node='$NodeExe' bridge='$Bridge' url='$Url' len=$($output.Length)"
    }

    $daemonMatch = [regex]::Match($output, '\[od-mcp-bridge\]\s+daemon\s+(\S+)')
    if ($daemonMatch.Success) { $result.Daemon = $daemonMatch.Groups[1].Value }

    if ($output -match '"name":"open-design"') {
        $result.Ok = $true
        $coreHits = ([regex]::Matches($output, '"(list_skills|list_projects|get_artifact|start_run)"')).Count
        $where = if ($result.Daemon) { "daemon $($result.Daemon)" } else { "no live daemon" }
        Write-Ok "MCP handshake OK (server 'open-design', $where); core tools found: $coreHits/4"
    } else {
        Write-Warn2 "MCP handshake did not return an 'open-design' serverInfo."
    }
    return $result
}

function Remove-OdInstall {
    foreach ($shim in $ShimFiles) {
        if (Test-Path $shim) { Remove-Item -LiteralPath $shim -Force; Write-Ok "removed $shim" }
    }
    foreach ($target in $ConfigTargets) {
        if (-not (Test-Path $target.Path)) { continue }
        try {
            $root = Get-Content $target.Path -Raw | ConvertFrom-Json
            if ($root.PSObject.Properties.Name -contains $target.Key) {
                $bucket = $root.($target.Key)
                $bucket.PSObject.Properties.Remove("open-design")
                # Drop the host key too when open-design was the only entry.
                if (@($bucket.PSObject.Properties).Count -eq 0) {
                    $root.PSObject.Properties.Remove($target.Key)
                }
            }
            if (@($root.PSObject.Properties).Count -eq 0) {
                Remove-Item -LiteralPath $target.Path -Force
                Write-Ok "removed $($target.Path)"
            } else {
                ($root | ConvertTo-Json -Depth 8) | Set-Content -Path $target.Path -Encoding UTF8
                Write-Ok "removed open-design from $($target.Path)"
            }
        } catch {
            Write-Warn2 "could not clean $($target.Path)"
        }
    }
    if (Test-Path $CodexConfig) {
        [void](Remove-CodexBlock)
        Write-Ok "removed open-design from $CodexConfig"
    }
}

# --- MAIN ---
Write-Host ""
Write-Host "Open Design MCP wiring (APC)" -ForegroundColor White
Write-Host "  repo: $RepoRoot" -ForegroundColor DarkGray

if ($Uninstall) {
    Write-Step "Removing Open Design MCP wiring"
    Remove-OdInstall
    Write-Host ""
    Write-Host "Done. Restart your agent host so the server disappears from its tool list." -ForegroundColor Green
    return
}

$odRoot = Find-OpenDesignInstall -Explicit $InstallRoot
$daemonCli = Join-Path $odRoot $DaemonCliRelative
$nodeExe = Find-NodeExe
Write-Ok "Open Design install: $odRoot"
Write-Ok "node: $nodeExe"

if (-not (Test-Path $BridgePath)) {
    throw "Missing $BridgePath - the MCP entry needs this port-discovery bridge."
}

Write-Step "Installing 'od' shim"
Install-OdShim -NodeExe $nodeExe -DaemonCli $daemonCli

Write-Step "Writing machine-local MCP configs (gitignored)"
foreach ($target in $ConfigTargets) {
    Set-McpConfig -ConfigPath $target.Path -RootKey $target.Key -NodeExe $nodeExe -Bridge $BridgePath -Url $DaemonUrl
}
Set-CodexConfig -NodeExe $nodeExe -Bridge $BridgePath -Url $DaemonUrl

$probe = [ordered]@{ Ok = $false; Daemon = "" }
if (-not $SkipVerify) {
    Write-Step "Verifying stdio handshake"
    $probe = Test-OdMcpServer -NodeExe $nodeExe -Bridge $BridgePath -Url $DaemonUrl
}

if ($probe.Daemon) {
    Write-Ok "Daemon discovered at $($probe.Daemon) - MCP tools are live."
} else {
    Write-Warn2 "No live OpenDesign daemon found. Open the Open Design app, then restart your agent host."
}

Write-Host ""
Write-Host "Next:" -ForegroundColor White
Write-Host "  1. Restart your agent host so it reloads MCP servers."
Write-Host "  2. Open the Open Design app and keep a project open for active-context tools."
Write-Host "  3. Docs: docs/open-design-mcp.md   Remove: -Uninstall"
Write-Host ""

